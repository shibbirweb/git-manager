// Swift for the native macOS (SwiftUI) library: colors that follow the system appearance, sizes as CGFloat and each
// component's measurements, named like the CSS ones (GMSize.control is --size-control).
import { parseShadow, parseTokenColor, type Rgba } from "./color";
import { camelName, pascalName, resolved, type Tokens } from "./model";

function rgba(color: Rgba): string {
  return `GMRGBA(${color.red}, ${color.green}, ${color.blue}, ${color.alpha})`;
}

const PRELUDE = `// Generated by \`bun run ui:tokens\` from ui/design-tokens; do not edit.
import AppKit
import SwiftUI

public struct GMRGBA: Sendable {
    public let red: Double, green: Double, blue: Double, alpha: Double
    public init(_ red: Double, _ green: Double, _ blue: Double, _ alpha: Double) {
        self.red = red; self.green = green; self.blue = blue; self.alpha = alpha
    }
    var nsColor: NSColor { NSColor(srgbRed: red / 255, green: green / 255, blue: blue / 255, alpha: alpha) }
}

public extension Color {
    /** A color that follows the light or dark appearance. */
    init(gmLight light: GMRGBA, dark: GMRGBA) {
        self.init(nsColor: NSColor(name: nil) { appearance in
            appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark.nsColor : light.nsColor
        })
    }
}

public struct GMShadow: Sendable {
    public let x: CGFloat, y: CGFloat, blur: CGFloat, light: GMRGBA, dark: GMRGBA
}`;

const WEIGHTS: Record<number, string> = { 400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold" };

/** The Swift type of a scale's values. */
function swiftType(scale: string, name: string): string {
  if (scale === "fontWeight") {
    return "Font.Weight";
  }
  if (scale === "motion" || scale === "lineHeight" || scale === "letterSpacing") {
    return "Double";
  }
  return (scale === "grid" && name === "columns") || scale === "textRows" ? "Int" : "CGFloat";
}

/** GMColors.swift: the colors, shadows and the helpers they need. */
export function colorsSwift(tokens: Tokens): string {
  const lines = [PRELUDE, "", "public enum GMColor {"];
  for (const [name, color] of Object.entries(tokens.colors)) {
    const light = rgba(parseTokenColor(color.light));
    lines.push(`    public static let ${camelName(name)} = Color(`);
    lines.push(`        gmLight: ${light}, dark: ${rgba(parseTokenColor(color.dark))})`);
  }
  lines.push("}", "", "public enum GMShadows {");
  for (const [name, shadow] of Object.entries(tokens.shadows)) {
    const light = parseShadow(shadow.light);
    const dark = parseShadow(shadow.dark);
    lines.push(
      `    public static let ${camelName(name)} = GMShadow(`,
      `        x: ${light.x}, y: ${light.y}, blur: ${light.blur}, ` +
        `light: ${rgba(light.color)}, dark: ${rgba(dark.color)})`,
    );
  }
  lines.push("}");
  lines.push(...paletteSwift(tokens));
  return `${lines.join("\n")}\n`;
}

/** The fixed palettes, appended to GMColors.swift. */
function paletteSwift(tokens: Tokens): string[] {
  const lines = ["", "public enum GMPalette {"];
  for (const [name, colors] of Object.entries(tokens.palettes)) {
    lines.push(`    public static let ${camelName(name)}: [GMRGBA] = [`);
    lines.push(...colors.map((color) => `        ${rgba(parseTokenColor(color))},`), "    ]");
  }
  lines.push("}");
  return lines;
}

/** GMMetrics.swift: fonts, sizes, radii, spacing, motion and each component's measurements. */
export function metricsSwift(tokens: Tokens): string {
  const lines = ["// Generated by `bun run ui:tokens` from ui/design-tokens; do not edit.", "import SwiftUI"];
  for (const [name, fonts] of Object.entries(tokens.fonts)) {
    lines.push("", `public enum GMFontFamily${pascalName(name)} {`);
    const names = fonts.map((font) => `        ${JSON.stringify(font)},`);
    lines.push("    public static let names = [", ...names, "    ]", "}");
  }
  for (const [scale, values] of Object.entries(tokens.scales)) {
    lines.push("", `public enum GM${pascalName(scale)} {`);
    for (const [name, value] of Object.entries(values)) {
      const type = swiftType(scale, name);
      const weight = WEIGHTS[value] ?? ".regular";
      const swiftValue = scale === "fontWeight" ? weight : scale === "motion" ? value / 1000 : value;
      lines.push(`    public static let ${camelName(name)}: ${type} = ${swiftValue}`);
    }
    lines.push("}");
  }
  return `${lines.join("\n")}\n`;
}

