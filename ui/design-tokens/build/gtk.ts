// GTK 4 CSS for a native Linux library: @define-color sheets for light and dark (load one with the appearance),
// and sizes plus component measurements as CSS variables (GTK 4.16 and later).
import { scalesCss, typographyCss } from "./css";
import { camelName, kebabName, type Mode, type Tokens } from "./model";

const HEADER = "/* Generated by `bun run ui:tokens` from ui/design-tokens; do not edit. */";

function gtkName(name: string): string {
  return `gm_${kebabName(camelName(name)).replace(/-/g, "_")}`;
}

export function colorsGtk(tokens: Tokens, mode: Mode): string {
  const lines = [HEADER];
  for (const [name, color] of Object.entries(tokens.colors)) {
    lines.push(`@define-color ${gtkName(name)} ${color[mode]};`);
  }
  return `${lines.join("\n")}\n`;
}

/** GTK 4 reads the same variables as the web: scales and typography here, components in chunked sheets. */
export function metricsGtk(tokens: Tokens): string {
  return scalesCss(tokens);
}

export function typographyGtk(tokens: Tokens): string {
  return typographyCss(tokens);
}
