/** One enum per component with its measurements (GMComponents*.swift). */
export function componentBlocksSwift(tokens: Tokens): string[][] {
  return Object.entries(tokens.components).map(([component, parts]) => [
    "",
    `public enum GM${pascalName(component)}Tokens {`,
    ...Object.entries(parts).map(
      ([part, value]) => `    public static let ${camelName(part)}: CGFloat = ${resolved(tokens, value)}`,
    ),
    "}",
  ]);
}

/** GMTypography.swift: the named text styles with size, weight, line height, tracking, case and family. */
export function typographySwift(tokens: Tokens): string {
  const lines = [
    "// Generated by `bun run ui:tokens` from ui/design-tokens; do not edit.",
    "import SwiftUI",
    "",
    "public struct GMTextStyle: Sendable {",
    "    public let family: [String]",
    "    public let size: CGFloat",
    "    public let weight: Font.Weight",
    "    /** A multiple of the size; nil for the normal line height. */",
    "    public let lineHeight: Double?",
    "    /** Letter spacing in em; tracking in points is letterSpacing * size. */",
    "    public let letterSpacing: Double",
    "    public let uppercase: Bool",
    "    /** A GMColor name for the text, or nil for the normal text color. */",
    "    public let tone: String?",
    "}",
    "",
    "public enum GMTextStyles {",
  ];
  for (const [name, style] of Object.entries(tokens.textStyles)) {
    const family = `GMFontFamily${pascalName(style.font)}.names`;
    const tone = style.tone ? `"text${pascalName(style.tone)}"` : "nil";
    lines.push(
      `    public static let ${camelName(name)} = GMTextStyle(`,
      `        family: ${family}, size: ${style.size}, weight: ${WEIGHTS[style.weight] ?? ".regular"},`,
      `        lineHeight: ${style.lineHeight ?? "nil"}, letterSpacing: ${style.letterSpacing}, ` +
        `uppercase: ${style.uppercase}, tone: ${tone})`,
    );
  }
  lines.push("}", "");
  return lines.join("\n");
}
