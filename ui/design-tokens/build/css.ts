// CSS for the Svelte library: sizes and component variables (tokens.css), and the colors (colors.css) that will
// replace the hand-written block in src/app.css once the app is generated from the tokens.
import { kebabName, type Mode, type Reference, type Tokens } from "./model";

/** The scales that belong to typography.css rather than scales.css. */
export const TYPE_SCALES = ["fontSize", "fontWeight", "lineHeight", "letterSpacing"];

const HEADER = "/* Generated by `bun run ui:tokens` from ui/design-tokens; do not edit. */";

/** A scale value with its CSS unit: ms for motion, em for letter spacing, none for counts and ratios. */
export function cssUnit(scale: string, name: string, value: number): string {
  if (scale === "motion") {
    return `${value}ms`;
  }
  if (scale === "letterSpacing") {
    return `${value}em`;
  }
  const unitless = scale === "fontWeight" || scale === "lineHeight" || (scale === "grid" && name === "columns");
  return unitless ? String(value) : `${value}px`;
}

/** A text style as CSS variables: --text-hint-size, -weight, -line-height, -letter-spacing, -transform, -family. */
export function textStyleLines(tokens: Tokens, indent: string): string[] {
  const lines: string[] = [];
  for (const [name, style] of Object.entries(tokens.textStyles)) {
    const prefix = `${indent}--text-${kebabName(name)}`;
    lines.push(
      `${prefix}-family: var(--font-family-${kebabName(style.font)});`,
      `${prefix}-size: ${style.size}px;`,
      `${prefix}-weight: ${style.weight};`,
      `${prefix}-line-height: ${style.lineHeight ?? "normal"};`,
      `${prefix}-letter-spacing: ${style.letterSpacing ? `${style.letterSpacing}em` : "normal"};`,
      `${prefix}-transform: ${style.uppercase ? "uppercase" : "none"};`,
    );
  }
  return lines;
}

/** A component part as CSS: a px number or a var() of the scale token it refers to. */
export function componentValue(value: number | Reference): string {
  return typeof value === "number" ? `${value}px` : `var(--${kebabName(value.group)}-${kebabName(value.name)})`;
}

/** tokens.css: the entry point the library and the app import; it pulls in the three generated sheets. */
export function tokensCss(): string {
  const sheets = ["scales", "typography", "components"].map((sheet) => `@import "./${sheet}.css";`);
  return [HEADER, ...sheets, ""].join("\n");
}

/** scales.css: sizes, radii, spacing, motion, breakpoints, grid and shadows. */
export function scalesCss(tokens: Tokens): string {
  const lines = [HEADER, ":root {"];
  for (const [scale, values] of Object.entries(tokens.scales)) {
    if (TYPE_SCALES.includes(scale)) {
      continue;
    }
    for (const [name, value] of Object.entries(values)) {
      lines.push(`  --${kebabName(scale)}-${kebabName(name)}: ${cssUnit(scale, name, value)};`);
    }
  }
  for (const [name, shadow] of Object.entries(tokens.shadows)) {
    lines.push(`  --shadow-${kebabName(name)}: ${shadow.light};`);
  }
  lines.push("}");
  const darkShadows = Object.entries(tokens.shadows).filter(([, shadow]) => shadow.dark !== shadow.light);
  if (darkShadows.length) {
    lines.push("", ":root[data-theme=\"dark\"] {");
    lines.push(...darkShadows.map(([name, shadow]) => `  --shadow-${kebabName(name)}: ${shadow.dark};`));
    lines.push("}", "", "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {");
    lines.push(...darkShadows.map(([name, shadow]) => `    --shadow-${kebabName(name)}: ${shadow.dark};`));
    lines.push("  }", "}");
  }
  return `${lines.join("\n")}\n`;
}

/** typography.css: font families, the type scales and every text style. */
export function typographyCss(tokens: Tokens): string {
  const lines = [HEADER, ":root {"];
  for (const scale of TYPE_SCALES) {
    for (const [name, value] of Object.entries(tokens.scales[scale] ?? {})) {
      lines.push(`  --${kebabName(scale)}-${kebabName(name)}: ${cssUnit(scale, name, value)};`);
    }
  }
  for (const [name, fonts] of Object.entries(tokens.fonts)) {
    const list = fonts.map((font) => (/\s/.test(font) ? `"${font}"` : font)).join(", ");
    lines.push(`  --font-family-${kebabName(name)}: ${list};`);
  }
  lines.push(...textStyleLines(tokens, "  "), "}");
  return `${lines.join("\n")}\n`;
}

/** components.css: each component's measurements. */
export function componentsCss(tokens: Tokens): string {
  const lines = [HEADER, ":root {"];
  for (const [component, parts] of Object.entries(tokens.components)) {
    for (const [part, value] of Object.entries(parts)) {
      lines.push(`  --${kebabName(component)}-${kebabName(part)}: ${componentValue(value)};`);
    }
  }
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

function colorBlock(tokens: Tokens, mode: Mode, indent: string): string[] {
  return Object.entries(tokens.colors).map(([name, color]) => `${indent}--${name}: ${color[mode]};`);
}

export function colorsCss(tokens: Tokens): string {
  return [
    HEADER,
    ":root {",
    ...colorBlock(tokens, "light", "  "),
    "}",
    "",
    ":root[data-theme=\"dark\"] {",
    ...colorBlock(tokens, "dark", "  "),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    "  :root:not([data-theme=\"light\"]) {",
    ...colorBlock(tokens, "dark", "    "),
    "  }",
    "}",
    "",
  ].join("\n");
}
