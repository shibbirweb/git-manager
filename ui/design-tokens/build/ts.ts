// TypeScript numbers for code that measures in script, such as a virtual list's row height, so it reads the same
// token as the CSS instead of a copied number.
import { chunkBlocks, chunkName } from "./chunks";
import { camelName, resolved, type Tokens } from "./model";

export interface TsFile {
  name: string;
  content: string;
}

const GENERATED = "// Generated by `bun run ui:tokens` from ui/design-tokens; do not edit.";

/** One component's object entry, on one line when it fits. */
function componentBlock(tokens: Tokens, component: string, parts: Tokens["components"][string]): string[] {
  const values = Object.entries(parts).map(([part, value]) => {
    return `${camelName(part)}: ${resolved(tokens, value)}`;
  });
  const line = `  ${camelName(component)}: { ${values.join(", ")} },`;
  const wrapped = [`  ${camelName(component)}: {`, ...values.map((value) => `    ${value},`), "  },"];
  return line.length <= 120 ? [line] : wrapped;
}

/**
 * tokens.ts and the component measurement files it joins (componentTokens.ts, componentTokens2.ts...), split so
 * each stays within the line limit.
 */
export function tokensTs(tokens: Tokens): TsFile[] {
  const blocks = Object.entries(tokens.components).map(([component, parts]) => {
    return componentBlock(tokens, component, parts);
  });
  const parts = chunkBlocks(blocks, 4).map((chunk, index) => ({
    name: chunkName("componentTokens", ".ts", index),
    exported: `componentTokens${index + 1}`,
    content: [GENERATED, `export const componentTokens${index + 1} = {`, ...chunk.flat(), "} as const;", ""].join("\n"),
  }));
  const lines = [
    GENERATED,
    ...parts.map((part) => `import { ${part.exported} } from "./${part.name.replace(/\.ts$/, "")}";`),
    "",
    "/** Component measurements in px for script; CSS reads the same values from tokens.css. */",
    `export const componentTokens = { ${parts.map((part) => `...${part.exported}`).join(", ")} } as const;`,
    "",
  ];
  lines.push("/** Every scale in px (or a count), for script that measures. Components pick these by name. */");
  lines.push("export const scales = {");
  for (const [scale, values] of Object.entries(tokens.scales)) {
    const entries = Object.entries(values).map(([name, value]) => `${camelName(name)}: ${value}`);
    const line = `  ${scale}: { ${entries.join(", ")} },`;
    const wrapped = [`  ${scale}: {`, ...entries.map((entry) => `    ${entry},`), "  },"];
    lines.push(...(line.length <= 120 ? [line] : wrapped));
  }
  lines.push("} as const;", "");
  lines.push("/** Window and panel widths in px where layouts change. */", "export const breakpoints = {");
  for (const [name, value] of Object.entries(tokens.scales.breakpoint ?? {})) {
    lines.push(`  ${camelName(name)}: ${value},`);
  }
  lines.push("} as const;", "", "export const grid = {");
  for (const [name, value] of Object.entries(tokens.scales.grid ?? {})) {
    lines.push(`  ${camelName(name)}: ${value},`);
  }
  lines.push("} as const;", "", "/** Each text style's tone (a Text tone) and whether it is monospace. */");
  lines.push("export const textStyles = {");
  for (const [name, style] of Object.entries(tokens.textStyles)) {
    const tone = style.tone ? `"${style.tone}"` : "null";
    lines.push(`  ${camelName(name)}: { tone: ${tone}, mono: ${style.font === "mono"} },`);
  }
  lines.push("} as const;", "", "export type TextStyleName = keyof typeof textStyles;", "");
  return [{ name: "tokens.ts", content: lines.join("\n") }, ...parts.map(({ name, content }) => ({ name, content }))];
}
